"""Data models for DBShield Test Execution subsystem (Phase 6).

Defines execution lifecycle states, execution records, run summaries,
and structured results for security test case tracking.
"""

import uuid
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from dbshield.sqli.models import ParameterLocation


class ExecutionStatus(StrEnum):
    """Lifecycle status of a scheduled security test case."""

    PENDING = "pending"
    RUNNING = "running"
    EXECUTED = "executed"
    SKIPPED = "skipped"
    FAILED = "failed"
    CANCELLED = "cancelled"


class ExecutionRecord(BaseModel):
    """Structured record of an individual payload test execution."""

    model_config = ConfigDict(frozen=True)

    execution_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique execution run UUID.",
    )
    test_case_id: str = Field(description="Identifier of the test case definition.")
    payload_id: str = Field(description="Identifier of the payload utilized.")
    parameter_name: str = Field(description="Target parameter name or dot-path.")
    parameter_location: ParameterLocation = Field(
        description="Transport location of the target parameter."
    )
    status: ExecutionStatus = Field(description="Final execution lifecycle state.")
    request_count: int = Field(
        default=0,
        description="Number of HTTP requests dispatched for this test case.",
    )
    elapsed_seconds: float = Field(
        default=0.0,
        description="Execution duration for this test case in seconds.",
    )
    status_code: int | None = Field(
        default=None,
        description="HTTP status code received on primary probe response.",
    )
    error_or_skip_reason: str | None = Field(
        default=None,
        description="Reason explanation when test case was skipped or failed.",
    )
    findings: list[Any] = Field(
        default_factory=list,
        description="Vulnerability findings generated by the associated engine detector.",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp when execution completed.",
    )


class ExecutionSummary(BaseModel):
    """Aggregated metrics for a test execution session."""

    model_config = ConfigDict(frozen=True)

    total_test_cases: int = Field(default=0, description="Total test cases scheduled.")
    executed_test_cases: int = Field(default=0, description="Test cases actively executed.")
    skipped_test_cases: int = Field(
        default=0, description="Test cases skipped (safety, policy, or budget)."
    )
    failed_test_cases: int = Field(
        default=0, description="Test cases failing due to transport or operational errors."
    )
    cancelled_test_cases: int = Field(
        default=0, description="Test cases cancelled due to early termination."
    )
    total_requests: int = Field(default=0, description="Total HTTP requests dispatched.")
    duration_seconds: float = Field(default=0.0, description="Total run duration in seconds.")


class ExecutionRunResult(BaseModel):
    """Immutable result of a complete test execution run."""

    model_config = ConfigDict(frozen=True)

    run_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique execution session UUID.",
    )
    target_url: str = Field(description="Primary target endpoint tested.")
    engine_name: str = Field(description="Engine or subsystem name executing tests.")
    execution_status: str = Field(default="completed", description="Overall run outcome.")
    summary: ExecutionSummary = Field(description="Aggregated execution metrics.")
    records: list[ExecutionRecord] = Field(
        default_factory=list,
        description="Detailed per-test-case execution records.",
    )
    findings: list[Any] = Field(
        default_factory=list,
        description="All findings collected across all executed test cases.",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp when execution run completed.",
    )
