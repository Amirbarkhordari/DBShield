"""Markdown report exporter for DBShield security reports (Phase 8).

Generates human-readable, professional GitHub-flavored Markdown reports.
"""

from __future__ import annotations

from dbshield.reporting.exporters.base import BaseReportExporter
from dbshield.reporting.models import SecurityAssessmentReport


class MarkdownReportExporter(BaseReportExporter):
    """Renders a structured SecurityAssessmentReport into GitHub-flavored Markdown."""

    def export(self, report: SecurityAssessmentReport) -> str:
        """Render report as clean, professional Markdown string."""
        meta = report.metadata
        lines: list[str] = [
            f"# {meta.title}",
            "",
            "> **CONFIDENTIAL SECURITY ASSESSMENT REPORT**",
            "> Generated by DBShield Automated Security Testing Framework",
            "",
            "## 1. Executive Summary",
            "",
            f"- **Target URL / Scope**: `{meta.target_url}`",
            f"- **Report Generated**: `{meta.generated_at.strftime('%Y-%m-%d %H:%M:%S UTC')}`",
            f"- **Report Identifier**: `{meta.report_id}`",
            f"- **Schema Version**: `{meta.version}`",
            f"- **Total Identified Findings**: `{meta.total_findings}`",
            "",
            "### Finding Breakdown by Severity",
            "",
            "| Severity | Total Findings | Description |",
            "| :--- | :---: | :--- |",
            f"| **CRITICAL** | {meta.findings_by_severity.get('critical', 0)} | High-impact direct authentication or authorization compromise |",
            f"| **HIGH** | {meta.findings_by_severity.get('high', 0)} | Formally verified or corroborated SQLi/NoSQLi database access |",
            f"| **MEDIUM** | {meta.findings_by_severity.get('medium', 0)} | Potential injection indicator pending verification |",
            f"| **LOW** | {meta.findings_by_severity.get('low', 0)} | Minor response variance or preliminary signal |",
            f"| **INFO** | {meta.findings_by_severity.get('info', 0)} | Benign false positive, rejected, or execution trace record |",
            "",
            "### Finding Breakdown by Verification Lifecycle Status",
            "",
            "| Verification Status | Count | Evaluation Meaning |",
            "| :--- | :---: | :--- |",
            f"| `verified` | {meta.findings_by_status.get('verified', 0)} | Meets documented criteria; database signature confirmed |",
            f"| `corroborated` | {meta.findings_by_status.get('corroborated', 0)} | Supported by independent detection signals |",
            f"| `potential_indicator` | {meta.findings_by_status.get('potential_indicator', 0)} | Initial signal observed by detection engine |",
            f"| `inconclusive` | {meta.findings_by_status.get('inconclusive', 0)} | Unstable baseline or chaotic differential noise |",
            f"| `rejected` | {meta.findings_by_status.get('rejected', 0)} | Confirmed benign/false positive (pre-existing in baseline) |",
            f"| `unverifiable` | {meta.findings_by_status.get('unverifiable', 0)} | Execution timeout, failure, or incomplete data |",
            "",
            "## 2. Detailed Findings",
            "",
        ]

        if not report.findings:
            lines.extend(
                [
                    "_No security findings were identified for the specified target and assessment scope._",
                    "",
                ]
            )
        else:
            for i, f in enumerate(report.findings, start=1):
                cwe_str = f"{f.cwe_id} — {f.cwe_name}" if f.cwe_id else "N/A"
                lines.extend(
                    [
                        f"### {i}. [{f.severity.value.upper()}] {f.title}",
                        "",
                        f"- **Finding ID**: `{f.id}`",
                        f"- **Category**: `{f.category.value}` ({f.subtype})",
                        f"- **Severity**: **{f.severity.value.upper()}**",
                        f"- **Verification Status**: `{f.verification_status.value}`",
                        f"- **Confidence**: `{f.confidence_level.value}` ({f.confidence_score:.2f})",
                        f"- **Target Endpoint**: `{f.endpoint}` ({f.http_method})",
                        f"- **Parameter**: `{f.parameter_name}` (location: `{f.parameter_location.value}`)",
                        f"- **CWE**: {cwe_str}",
                        "",
                        "#### Evidence & Technical Observations",
                        "",
                        f"> {f.evidence_summary}",
                        "",
                        f"- **Severity Rationale**: {f.severity_rationale}",
                        f"- **Corroborating Records Count**: {f.evidence_count}",
                        "",
                        "#### Actionable Remediation",
                        "",
                        f"{f.remediation}",
                        "",
                        "---",
                        "",
                    ]
                )

        lines.extend(
            [
                "## 3. Scope and Limitations",
                "",
                "### Authorized Target Scope",
                "",
            ]
        )
        for s in meta.assessment_scope:
            lines.append(f"- `{s}`")
        lines.append("")

        lines.extend(
            [
                "### Assessment Boundaries & Safety Disclaimers",
                "",
            ]
        )
        if meta.limitations:
            for lim in meta.limitations:
                lines.append(f"- {lim}")
        else:
            lines.extend(
                [
                    "- Automated assessment strictly observes response variations without active exploitation.",
                    "- Verification status distinguishes confirmed vulnerabilities from preliminary signals and baseline noise.",
                    "- Inconclusive findings require manual confirmation before structural remediation is undertaken.",
                ]
            )
        lines.append("")

        return "\n".join(lines)
